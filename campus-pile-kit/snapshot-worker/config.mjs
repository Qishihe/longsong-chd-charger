/** 北京时间的「小时」与「星期几」。UTC+8 是整小时偏移，所以分钟数通用。 */
export function beijingHour(ts) {
  return new Date((ts + 8 * 3600) * 1000).getUTCHours();
}

export function beijingWeekday(ts) {
  return new Date((ts + 8 * 3600) * 1000).getUTCDay(); // 0 = 周日
}

/** 某一时刻的目标刷新间隔（秒）。 */
export function intervalFor(ts, schedule = SCHEDULE) {
  const hour = beijingHour(ts);
  const table = beijingWeekday(ts) === 0 || beijingWeekday(ts) === 6 ? schedule.weekend : schedule.weekday;
  const minutes = Math.max(MIN_INTERVAL_MIN, table[hour] ?? 15);
  return minutes * 60;
}

/** 这一跳该不该跑：把「每 N 分钟」折算成「分钟数对 N 取模是否等于偏移」。 */
export function shouldRunAt(ts, offsetMinute, schedule = SCHEDULE) {
  const intervalMin = Math.max(MIN_INTERVAL_MIN, Math.round(intervalFor(ts, schedule) / 60));
  const minute = new Date((ts + 8 * 3600) * 1000).getUTCMinutes();
  return minute % intervalMin === offsetMinute % intervalMin;
}

/**
 * 补跑判定：上一次「该跑的那跳」是不是没跑成。
 *
 * 抽成纯函数是为了能单测 —— 这是「丢跳静默」这个事故形状唯一能被测到
 * 的地方，塞在 worker.mjs 里就只能靠肉眼review。
 *
 * @param ageSec     快照年龄。缺失/无效（Infinity、NaN、null）一律返回
 *                   false：那说明**从来没有成功过**，属于首次部署而不是
 *                   漏跑，交给正常日历那一跳去做（它 5 分钟内必到）。
 * @param intervalSec 当前时段的目标间隔（intervalFor 的返回值）。
 */
export function catchupNeeded(ageSec, intervalSec, tuning = TUNING) {
  if (!tuning.CRON_CATCHUP_ENABLED) return false;
  if (!Number.isFinite(intervalSec) || intervalSec <= 0) return false;
  if (!Number.isFinite(ageSec)) return false;
  return ageSec >= intervalSec + tuning.CRON_CATCHUP_GRACE_S;
}
